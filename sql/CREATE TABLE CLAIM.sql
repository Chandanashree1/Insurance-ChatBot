CREATE TABLE CLAIM (
    CLAIM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    POLICY_ID NUMBER,
    CLAIM_NUMBER VARCHAR2(20),
    CLAIM_DATE DATE,
    CLAIM_TYPE VARCHAR2(50),
    CLAIM_AMOUNT NUMBER,
    APPROVED_AMOUNT NUMBER,
    STATUS VARCHAR2(20),

    CONSTRAINT FK_POLICY
    FOREIGN KEY (POLICY_ID)
    REFERENCES POLICY(POLICY_ID)
);
