CREATE TABLE POLICY (
    POLICY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,

    POLICY_NUMBER VARCHAR2(50) NOT NULL,

    QUOTE_ID NUMBER NOT NULL,
    CUSTOMER_ID NUMBER NOT NULL,
    VEHICLE_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    OPTION_ID NUMBER NOT NULL,

    PREMIUM NUMBER(15,3) NOT NULL,

    COVER_FROM DATE NOT NULL,
    COVER_TO DATE NOT NULL,

    POLICY_STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_POLICY
        PRIMARY KEY (POLICY_ID),

    CONSTRAINT UK_POLICY_NUMBER
        UNIQUE (POLICY_NUMBER),

    CONSTRAINT FK_POLICY_QUOTE
        FOREIGN KEY (QUOTE_ID)
        REFERENCES QUOTE(QUOTE_ID),

    CONSTRAINT FK_POLICY_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER(CUSTOMER_ID),

    CONSTRAINT FK_POLICY_VEHICLE
        FOREIGN KEY (VEHICLE_ID)
        REFERENCES VEHICLE(VEHICLE_ID),

    CONSTRAINT FK_POLICY_PRODUCT
        FOREIGN KEY (PRODUCT_ID)
        REFERENCES PRODUCT(PRODUCT_ID),

    CONSTRAINT FK_POLICY_OPTION
        FOREIGN KEY (OPTION_ID)
        REFERENCES QUOTE_OPTION(OPTION_ID),

    CONSTRAINT CK_POLICY_STATUS
        CHECK (POLICY_STATUS IN (
            'ACTIVE',
            'EXPIRED',
            'CANCELLED'
        )),

    CONSTRAINT CK_POLICY_PREMIUM
        CHECK (PREMIUM >= 0)
);
