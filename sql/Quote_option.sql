CREATE TABLE QUOTE_OPTION (
    OPTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,

    QUOTE_ID NUMBER NOT NULL,

    OPTION_NUMBER NUMBER(1) NOT NULL,

    PLAN_NAME VARCHAR2(150) NOT NULL,

    PREMIUM NUMBER(15,3) NOT NULL,

    COVERAGE_DETAILS VARCHAR2(1000),

    IS_SELECTED CHAR(1) DEFAULT 'N' NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_QUOTE_OPTION
        PRIMARY KEY (OPTION_ID),

    CONSTRAINT FK_QUOTE_OPTION_QUOTE
        FOREIGN KEY (QUOTE_ID)
        REFERENCES QUOTE(QUOTE_ID),

    CONSTRAINT UK_QUOTE_OPTION_NUMBER
        UNIQUE (QUOTE_ID, OPTION_NUMBER),

    CONSTRAINT CK_OPTION_NUMBER
        CHECK (OPTION_NUMBER BETWEEN 1 AND 4),

    CONSTRAINT CK_OPTION_SELECTED
        CHECK (IS_SELECTED IN ('Y', 'N')),

    CONSTRAINT CK_OPTION_PREMIUM
        CHECK (PREMIUM >= 0)
);
