CREATE TABLE POLICY (
    POLICY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    POLICY_NUMBER VARCHAR2(20) UNIQUE,
    CUSTOMER_ID NUMBER,
    POLICY_TYPE VARCHAR2(30),
    PLAN_NAME VARCHAR2(100),
    PREMIUM NUMBER,
    SUM_INSURED NUMBER,
    START_DATE DATE,
    END_DATE DATE,
    STATUS VARCHAR2(20),

    CONSTRAINT FK_CUSTOMER
    FOREIGN KEY (CUSTOMER_ID)
    REFERENCES CUSTOMER(CUSTOMER_ID)
);
