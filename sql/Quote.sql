--Proposal Table --
CREATE TABLE PROPOSAL (
    PROPOSAL_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,

    PROPOSAL_NUMBER VARCHAR2(50) NOT NULL,

    QUOTE_ID NUMBER NOT NULL,
    OPTION_ID NUMBER NOT NULL,

    PROPOSAL_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,

    UNDERWRITER_NOTE VARCHAR2(1000),

    COUNTER_OFFER_PREMIUM NUMBER(15,3),

    SUBMITTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    DECIDED_AT TIMESTAMP,

    CONSTRAINT PK_PROPOSAL
        PRIMARY KEY (PROPOSAL_ID),

    CONSTRAINT UK_PROPOSAL_NUMBER
        UNIQUE (PROPOSAL_NUMBER),

    CONSTRAINT FK_PROPOSAL_QUOTE
        FOREIGN KEY (QUOTE_ID)
        REFERENCES QUOTE(QUOTE_ID),

    CONSTRAINT FK_PROPOSAL_OPTION
        FOREIGN KEY (OPTION_ID)
        REFERENCES QUOTE_OPTION(OPTION_ID),

    CONSTRAINT CK_PROPOSAL_STATUS
        CHECK (PROPOSAL_STATUS IN (
            'PENDING',
            'APPROVED',
            'COUNTER_OFFER',
            'DECLINED'
        ))
);



