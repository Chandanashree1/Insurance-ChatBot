CREATE TABLE QUOTE (
    QUOTE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,

    QUOTE_NUMBER VARCHAR2(50) NOT NULL,

    CUSTOMER_ID NUMBER NOT NULL,
    VEHICLE_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,

    VEHICLE_VALUE NUMBER(15,3),

    COVER_FROM DATE NOT NULL,
    COVER_TO DATE NOT NULL,

    QUOTE_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,

    PAYMENT_STATUS VARCHAR2(20) DEFAULT 'NOT_PAID' NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_QUOTE
        PRIMARY KEY (QUOTE_ID),

    CONSTRAINT UK_QUOTE_NUMBER
        UNIQUE (QUOTE_NUMBER),

    CONSTRAINT FK_QUOTE_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER(CUSTOMER_ID),

    CONSTRAINT FK_QUOTE_VEHICLE
        FOREIGN KEY (VEHICLE_ID)
        REFERENCES VEHICLE(VEHICLE_ID),

    CONSTRAINT FK_QUOTE_PRODUCT
        FOREIGN KEY (PRODUCT_ID)
        REFERENCES PRODUCT(PRODUCT_ID),

    CONSTRAINT CK_QUOTE_STATUS
        CHECK (QUOTE_STATUS IN (
            'PENDING',
            'CONVERTED',
            'EXPIRED'
        )),

    CONSTRAINT CK_PAYMENT_STATUS
        CHECK (PAYMENT_STATUS IN (
            'NOT_PAID',
            'PAID',
            'FAILED'
        ))
);
