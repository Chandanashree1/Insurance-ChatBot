CREATE TABLE VEHICLE (
    VEHICLE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CUSTOMER_ID NUMBER NOT NULL,
    PLATE_NUMBER VARCHAR2(20) NOT NULL,
    PLATE_CODE VARCHAR2(10) NOT NULL,
    PLATE_TYPE VARCHAR2(30) NOT NULL,
    MAKE VARCHAR2(50) NOT NULL,
    MODEL VARCHAR2(50) NOT NULL,
    YEAR NUMBER(4) NOT NULL,
    CHASSIS_NUMBER VARCHAR2(50) NOT NULL,
    BODY_TYPE VARCHAR2(30) NOT NULL,
    USAGE_TYPE VARCHAR2(30) NOT NULL,

    CONSTRAINT PK_VEHICLE
        PRIMARY KEY (VEHICLE_ID),

    CONSTRAINT FK_VEHICLE_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER(CUSTOMER_ID),

    CONSTRAINT UK_VEHICLE_PLATE
        UNIQUE (PLATE_NUMBER, PLATE_CODE)
);
